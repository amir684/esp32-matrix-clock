#pragma once
// 8-pixel-high rounded proportional font: Hebrew letters, digits and a little punctuation.
// The Hebrew shapes follow the Fredoka typeface (regular weight), scaled to 7 rows and cleaned by hand.
// Each glyph is drawn as rows top to bottom; '#' = LED on. Rows 0-6 are the body,
// row 7 is for descenders (ך ן ף ץ ק). Missing rows are blank. Edit freely.
// The bold version is in font_bold.h; the clock picks one of the two from its settings.
#include <stdint.h>

