# Runs before every PlatformIO build (or by hand: python tools/embed_web.py):
#  1. packs web/index.html (gzip) into src/web_page.h, so the clock serves it from flash;
#  2. copies it to docs/ for GitHub Pages, where it runs as the installable Bluetooth app,
#     and stamps docs/sw.js with the page's hash so phones pick up a new version.
import gzip, hashlib, os

try:
    Import("env")  # noqa: F821 - provided by PlatformIO
    root = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def write_if_changed(path, text, binary=False):
    mode = "rb" if binary else "r"
    if os.path.exists(path):
        old = open(path, mode) if binary else open(path, encoding="utf-8")
        with old:
            if old.read() == text:
                return False
    if binary:
        open(path, "wb").write(text)
    else:
        open(path, "w", encoding="utf-8", newline="\n").write(text)
    return True


src = os.path.join(root, "web", "index.html")
page = open(src, "rb").read()

# 1. firmware
data = gzip.compress(page, 9, mtime=0)
lines = ["#pragma once",
         "// Generated from web/index.html by tools/embed_web.py. Do not edit by hand.",
         "#include <Arduino.h>",
         "",
         "static const size_t WEB_PAGE_GZ_LEN = %d;" % len(data),
         "static const uint8_t WEB_PAGE_GZ[] PROGMEM = {"]
for i in range(0, len(data), 20):
    lines.append("    " + ",".join(str(b) for b in data[i:i + 20]) + ",")
lines.append("};")
if write_if_changed(os.path.join(root, "src", "web_page.h"), "\n".join(lines) + "\n"):
    print("embed_web: index.html -> %d bytes gzipped" % len(data))

# 2. GitHub Pages
docs = os.path.join(root, "docs")
if os.path.isdir(docs):
    write_if_changed(os.path.join(docs, "index.html"), page, binary=True)
    version = hashlib.sha1(page).hexdigest()[:10]
    sw = ("// Offline cache for the installed app. Generated by tools/embed_web.py: the version is the page's hash,\n"
          "// so a new page replaces the cached one.\n"
          "const C = 'matrix-clock-%s', F = ['./', 'index.html', 'manifest.webmanifest', 'icon.svg'];\n"
          "self.addEventListener('install', e => { self.skipWaiting(); e.waitUntil(caches.open(C).then(c => c.addAll(F))); });\n"
          "self.addEventListener('activate', e => e.waitUntil(caches.keys().then(k => Promise.all(k.filter(x => x !== C).map(x => caches.delete(x)))).then(() => self.clients.claim())));\n"
          "self.addEventListener('fetch', e => {\n"
          "  if (e.request.method !== 'GET') return;\n"
          "  e.respondWith(fetch(e.request).then(r => { const c = r.clone(); caches.open(C).then(x => x.put(e.request, c)); return r; })\n"
          "    .catch(() => caches.match(e.request, { ignoreSearch: true })));\n"
          "});\n" % version)
    write_if_changed(os.path.join(docs, "sw.js"), sw)
